create or replace function public.official_offline_isodow(p_date date)
returns integer
language plpgsql
immutable
as $$
declare
  v_monday date := date_trunc('week', p_date)::date;
  v_previous date := v_monday - 7;
  v_day integer;
  v_previous_day integer;
  v_hex text;
begin
  -- Stable pseudo-random weekday, 1..5, based on the week.
  v_hex := md5(v_monday::text);
  v_day := (get_byte(decode(substr(v_hex,1,2),'hex'),0) % 5) + 1;

  v_hex := md5(v_previous::text);
  v_previous_day := (get_byte(decode(substr(v_hex,1,2),'hex'),0) % 5) + 1;

  -- Avoid repeating the same offline weekday in consecutive weeks.
  if v_day = v_previous_day then
    v_day := case when v_day = 5 then 1 else v_day + 1 end;
  end if;

  return v_day;
end;
$$;

revoke all on function public.official_offline_isodow(date) from public;

