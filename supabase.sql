create or replace function public.admin_add_day_off_shift(
  p_token text,
  p_off_date date
)
returns jsonb
language plpgsql
security definer
set search_path=public,extensions,pg_catalog
as $$
declare
  v_date date;
  v_target date;
  v_groups integer:=0;
  v_group record;
begin
  if not public.is_admin_token(p_token) then
    raise exception 'Session admin invalide';
  end if;

  insert into public.planner_day_offs(off_date)
  values(p_off_date)
  on conflict(off_date) do nothing;

  -- Process from latest date to earliest date. This prevents a shift
  -- from colliding with a later uncompleted group that still needs moving.
  for v_group in
    select study_date
    from public.study_sessions_v2
    where study_date >= p_off_date
      and completed=false
    group by study_date
    order by study_date desc
  loop

    v_date:=v_group.study_date;
    v_target:=v_date+1;

    while extract(isodow from v_target)::integer in (6,7)
       or exists(
         select 1
         from public.planner_day_offs d
         where d.off_date=v_target
       )
    loop
      v_target:=v_target+1;
    end loop;

    update public.study_sessions_v2
    set study_date=v_target
    where study_date=v_date
      and completed=false;

    v_groups:=v_groups+1;
  end loop;

  return jsonb_build_object(
    'ok',true,
    'off_date',p_off_date,
    'shifted_groups',v_groups
  );
end;
$$;

