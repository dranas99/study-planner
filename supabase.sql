create or replace function public.admin_move_course(p_token text, p_course_id bigint, p_direction integer)
returns boolean
language plpgsql
security definer
set search_path = public, pg_catalog
as $$
declare
  v_current integer;
  v_other_id bigint;
  v_other integer;
begin
  if not public.is_admin_token(p_token) then raise exception 'Session admin invalide'; end if;
  select global_order into v_current from public.courses_v2 where id=p_course_id;
  if v_current is null then raise exception 'Cours introuvable'; end if;

  if p_direction < 0 then
    select id,global_order into v_other_id,v_other
    from public.courses_v2
    where global_order < v_current
    order by global_order desc
    limit 1;
  else
    select id,global_order into v_other_id,v_other
    from public.courses_v2
    where global_order > v_current
    order by global_order asc
    limit 1;
  end if;

  if v_other_id is null then return true; end if;

  update public.courses_v2 set global_order = -global_order where id in (p_course_id,v_other_id);
  update public.courses_v2 set global_order = v_other where id=p_course_id;
  update public.courses_v2 set global_order = v_current where id=v_other_id;
  return true;
end;
$$;

grant execute on function public.admin_move_course(text,bigint,integer) to anon;

