-- 3) Resize a course safely.
--    - Updates the requested course's planned days.
--    - Preserves completed days.
--    - Adds missing future sessions when needed.
--    - Removes only future sessions without timer logs.
--    - Reorders future sessions without deleting the rest.
create or replace function public.admin_resize_course_schedule(
  p_token text,
  p_session_id uuid,
  p_new_days integer,
  p_duration_min integer,
  p_notes text,
  p_completed boolean
)
returns integer
language plpgsql
security definer
set search_path = public,extensions,pg_catalog
as $$
declare
  v_course_id bigint;
  v_new_days integer := greatest(1,least(30,coalesce(p_new_days,1)));
  v_completed_count integer;
  v_incomplete_count integer;
  v_needed integer;
  v_extra integer;
  v_date date;
  v_i integer;
begin
  if not public.is_admin_token(p_token) then
    raise exception 'Session admin invalide';
  end if;

  select course_id
  into v_course_id
  from public.study_sessions_v2
  where id=p_session_id;

  if v_course_id is null then
    raise exception 'Séance introuvable';
  end if;

  -- Update the edited session itself.
  update public.study_sessions_v2
  set completed=coalesce(p_completed,false),
      notes=nullif(trim(coalesce(p_notes,'')),''),
      planned_days=v_new_days,
      duration_min=greatest(0,coalesce(p_duration_min,0))
  where id=p_session_id;

  update public.courses_v2
  set planned_days=v_new_days,
      default_duration_min=greatest(0,coalesce(p_duration_min,0)),
      default_notes=nullif(trim(coalesce(p_notes,'')),'')
  where id=v_course_id;

  select count(*)
  into v_completed_count
  from public.study_sessions_v2
  where course_id=v_course_id
    and completed=true;

  select count(*)
  into v_incomplete_count
  from public.study_sessions_v2
  where course_id=v_course_id
    and completed=false;

  v_needed:=greatest(0,v_new_days-v_completed_count);

  -- Add missing future sessions.
  if v_incomplete_count < v_needed then
    v_extra:=v_needed-v_incomplete_count;

    select coalesce(max(study_date)+1, current_date+1)
    into v_date
    from public.study_sessions_v2;

    for v_i in 1..v_extra loop
      insert into public.study_sessions_v2(
        course_id,study_date,mode,duration_min,notes,planned_days,completed
      )
      values(
        v_course_id,
        v_date,
        case
          when extract(isodow from v_date)::integer=3 then 'offline'
          else 'online'
        end,
        0,
        nullif(trim(coalesce(p_notes,'')),''),
        v_new_days,
        false
      );
      v_date:=v_date+1;
    end loop;
  end if;

  -- Remove surplus future sessions only if they have NO timer log.
  if v_incomplete_count > v_needed then
    v_extra:=v_incomplete_count-v_needed;

    delete from public.study_sessions_v2 s
    where s.id in (
      select s2.id
      from public.study_sessions_v2 s2
      where s2.course_id=v_course_id
        and s2.completed=false
        and not exists(
          select 1
          from public.study_time_logs l
          where l.session_id=s2.id
        )
      order by s2.study_date desc, s2.id desc
      limit v_extra
    );
  end if;

  -- If logged sessions prevent pruning, do not delete them.
  return public.rebuild_schedule_internal();
end;
$$;

grant execute
on function public.admin_resize_course_schedule(text,uuid,integer,integer,text,boolean)
to anon;

-- 4) Initial seed: only when there are truly no sessions.
create or replace function public.admin_seed_initial_schedule(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = public,extensions,pg_catalog
as $$
declare
  v_start date;
  v_cursor date;
  v_created integer:=0;
  v_course record;
  v_days integer;
  v_i integer;
begin
  if not public.is_admin_token(p_token) then
    return jsonb_build_object('ok',false,'error','Session admin invalide');
  end if;

  if exists(select 1 from public.study_sessions_v2) then
    return jsonb_build_object(
      'ok',true,
      'created',false,
      'reason','sessions_exist',
      'count',(select count(*) from public.study_sessions_v2)
    );
  end if;

  select coalesce(start_date,date '2026-09-17')
  into v_start
  from public.planner_settings
  where id=1;

  v_cursor:=v_start;

  for v_course in
    select id, greatest(1,least(30,coalesce(planned_days,1))) as planned_days
    from public.courses_v2
    order by global_order nulls last,id
  loop
    v_days:=v_course.planned_days;

    for v_i in 1..v_days loop
      while extract(isodow from v_cursor)::integer in (6,7)
         or exists(
           select 1 from public.planner_day_offs d where d.off_date=v_cursor
         )
      loop
        v_cursor:=v_cursor+1;
      end loop;

      insert into public.study_sessions_v2(
        course_id,study_date,mode,duration_min,notes,planned_days,completed
      )
      values(
        v_course.id,
        v_cursor,
        case
          when extract(isodow from v_cursor)::integer=official_offline_isodow(v_cursor)
            then 'offline'
          else 'online'
        end,
        0,
        null,
        v_days,
        false
      );

      v_created:=v_created+1;
      v_cursor:=v_cursor+1;
    end loop;
  end loop;

  return jsonb_build_object(
    'ok',true,
    'created',true,
    'count',v_created,
    'start_date',v_start
  );
end;
$$;

grant execute
on function public.admin_seed_initial_schedule(text)
to anon;

-- 5) Safe "restore original order".
--    IMPORTANT: it does not delete sessions or rebuild completed history.
create or replace function public.admin_restore_original_order(
  p_token text
)
returns jsonb
language plpgsql
security definer
set search_path=public,extensions,pg_catalog
as $$
declare
  v_start date;
  v_count integer;
begin
  if not public.is_admin_token(p_token) then
    raise exception 'Session admin invalide';
  end if;

  select coalesce(start_date,date '2026-09-17')
  into v_start
  from public.planner_settings
  where id=1;

  with ranked as(
    select
      c.id,
      row_number() over(
        order by
          case
            when lower(coalesce(c.professor,'')) like '%saadi%' then 1
            when lower(coalesce(c.professor,'')) like '%mimouni%' then 2
            when lower(coalesce(c.professor,'')) like '%tahiri%' then 3
            else 4
          end,
          c.sort_order,
          c.id
      ) as rn
    from public.courses_v2 c
  )
  update public.courses_v2 c
  set global_order=r.rn
  from ranked r
  where c.id=r.id;

  -- Reset future Day Off markers without touching historical dates.
  delete from public.planner_day_offs
  where off_date>=v_start;

  -- Reorder existing incomplete sessions only.
  v_count:=public.rebuild_schedule_internal();

  return jsonb_build_object(
    'ok',true,
    'reordered_sessions',v_count,
    'message','Ordre Saadi → Mimouni → Tahiri restauré; progression conservée.'
  );
end;
$$;

grant execute
on function public.admin_restore_original_order(text)
to anon;

