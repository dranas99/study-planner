create or replace function public.admin_undo_last_planner_action(
  p_token text
)
returns jsonb
language plpgsql
security definer
set search_path=public,pg_catalog
as $$
declare
  v_row public.planner_change_history%rowtype;
  v_current jsonb;
  v_before jsonb;
  v_after jsonb;
  v_id uuid;
  v_json jsonb;
begin
  if not public.is_admin_token(p_token) then
    raise exception 'Session admin invalide';
  end if;

  select *
  into v_row
  from public.planner_change_history
  where undone_at is null
  order by id desc
  limit 1
  for update;

  if v_row.id is null then
    return jsonb_build_object('ok',false,'message','Aucune modification à annuler.');
  end if;

  v_current:=public._planner_snapshot();

  -- Do not silently overwrite a newer change made by another client.
  if v_current <> v_row.after_state then
    raise exception 'Le planning a changé depuis cette modification. Annulation interrompue pour protéger les données.';
  end if;

  v_before:=v_row.before_state;
  v_after:=v_row.after_state;

  -- Restore Day Off dates exactly as they were.
  delete from public.planner_day_offs where true;

  insert into public.planner_day_offs(off_date,created_at)
  select
    (x->>'off_date')::date,
    coalesce((x->>'created_at')::timestamptz,now())
  from jsonb_array_elements(coalesce(v_before->'dayoffs','[]'::jsonb)) x
  on conflict(off_date) do nothing;

  -- Restore existing sessions in place. This preserves UUIDs and time-log links.
  for v_json in
    select value
    from jsonb_array_elements(coalesce(v_before->'sessions','[]'::jsonb))
  loop
    v_id:=(v_json->>'id')::uuid;

    update public.study_sessions_v2
    set course_id=(v_json->>'course_id')::bigint,
        study_date=(v_json->>'study_date')::date,
        mode=v_json->>'mode',
        duration_min=coalesce((v_json->>'duration_min')::integer,0),
        notes=v_json->>'notes',
        planned_days=coalesce((v_json->>'planned_days')::integer,1),
        completed=coalesce((v_json->>'completed')::boolean,false)
    where id=v_id;

    if not found then
      insert into public.study_sessions_v2(
        id,course_id,study_date,mode,duration_min,notes,planned_days,completed,created_at
      )
      values(
        v_id,
        (v_json->>'course_id')::bigint,
        (v_json->>'study_date')::date,
        v_json->>'mode',
        coalesce((v_json->>'duration_min')::integer,0),
        v_json->>'notes',
        coalesce((v_json->>'planned_days')::integer,1),
        coalesce((v_json->>'completed')::boolean,false),
        coalesce((v_json->>'created_at')::timestamptz,now())
      );
    end if;
  end loop;

  -- Remove sessions created by the action, but never remove a session
  -- that already has a time log.
  for v_json in
    select value
    from jsonb_array_elements(coalesce(v_after->'sessions','[]'::jsonb))
    where not exists (
      select 1
      from jsonb_array_elements(coalesce(v_before->'sessions','[]'::jsonb)) b
      where b->>'id'=value->>'id'
    )
  loop
    v_id:=(v_json->>'id')::uuid;

    if exists(select 1 from public.study_time_logs l where l.session_id=v_id) then
      raise exception 'Cette séance possède déjà un enregistrement de chrono. Annulation refusée pour protéger le temps étudié.';
    end if;

    delete from public.study_sessions_v2
    where id=v_id;
  end loop;

  update public.planner_change_history
  set undone_at=now()
  where id=v_row.id;

  return jsonb_build_object(
    'ok',true,
    'id',v_row.id,
    'label',v_row.label
  );
end;
$$;

