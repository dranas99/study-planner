create or replace function public.rebuild_schedule_internal()
returns integer
language plpgsql
security definer
set search_path = public, extensions, pg_catalog
as $$
declare
  v_start date;
  v_date date;
  v_offline_dow integer;
  v_course record;
  v_days integer;
  v_completed integer;
  v_duration integer;
  v_notes text;
  v_created integer := 0;
begin
  select start_date into v_start from public.planner_settings where id=1;
  v_start := coalesce(v_start, date '2026-09-17');
  v_date := v_start;

  create temp table tmp_course_meta(
    course_id bigint primary key,
    days integer,
    completed_count integer,
    duration_min integer,
    notes text
  ) on commit drop;

  insert into tmp_course_meta(course_id,days,completed_count,duration_min,notes)
  select
    c.id,
    greatest(1, least(30, coalesce(c.planned_days,1))),
    greatest(0, coalesce(sum(case when s.completed then 1 else 0 end),0)),
    greatest(0, coalesce(c.default_duration_min,90)),
    c.default_notes
  from public.courses_v2 c
  left join public.study_sessions_v2 s on s.course_id=c.id
  group by c.id, c.planned_days, c.default_duration_min, c.default_notes;

  delete from public.study_sessions_v2 where true;

  for v_course in
    select id from public.courses_v2 order by global_order nulls last, id
  loop
    select days,completed_count,duration_min,notes
    into v_days,v_completed,v_duration,v_notes
    from tmp_course_meta where course_id=v_course.id;

    v_days := greatest(1,least(30,coalesce(v_days,1)));

    for i in 1..v_days loop
      -- Automatic planning uses weekdays only. Weekends stay empty unless the user manually adds a session.
      while extract(isodow from v_date)::integer > 5 loop
        v_date := v_date + 1;
      end loop;

      if extract(isodow from v_date)::integer = public.official_offline_isodow(v_date) then
        insert into public.study_sessions_v2(course_id,study_date,mode,duration_min,notes,planned_days,completed)
        values(v_course.id,v_date,'offline',coalesce(v_duration,90),v_notes,v_days,i <= least(v_completed,v_days));
      else
        insert into public.study_sessions_v2(course_id,study_date,mode,duration_min,notes,planned_days,completed)
        values(v_course.id,v_date,'online',coalesce(v_duration,90),v_notes,v_days,i <= least(v_completed,v_days));
      end if;
      v_created := v_created + 1;
      v_date := v_date + 1;
    end loop;
  end loop;

  return v_created;
end;
$$;

revoke all on function public.rebuild_schedule_internal() from public;

