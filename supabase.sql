-- Default subject if none exists.
insert into public.subjects(name, sort_order)
select 'Gynécologie-obstétrique', 1
where not exists (select 1 from public.subjects);

-- Backfill global_order for any old courses that do not have one.
with ranked as (
  select
    c.id,
    row_number() over (
      order by
        coalesce(s.sort_order, 999999),
        coalesce(c.sort_order, 999999),
        c.id
    ) as rn
  from public.courses_v2 c
  left join public.subjects s on s.id = c.subject_id
  where c.global_order is null
)
update public.courses_v2 c
set global_order = ranked.rn
from ranked
where c.id = ranked.id;

-- Normalize the complete global order so every course has a unique position.
with normalized as (
  select id, row_number() over (order by global_order nulls last, id) as rn
  from public.courses_v2
)
update public.courses_v2 c
set global_order = normalized.rn
from normalized
where c.id = normalized.id;

-- Persist the current planning metadata at course level.
with meta as (
  select
    c.id,
    greatest(1, coalesce(max(s.planned_days), c.planned_days, 1)) as days,
    greatest(0, coalesce(max(s.duration_min), c.default_duration_min, 90)) as duration_min,
    max(s.notes) as notes
  from public.courses_v2 c
  left join public.study_sessions_v2 s on s.course_id = c.id
  group by c.id, c.planned_days, c.default_duration_min
)
update public.courses_v2 c
set planned_days = meta.days,
    default_duration_min = meta.duration_min,
    default_notes = coalesce(meta.notes, c.default_notes)
from meta
where c.id = meta.id;

-- If the table was empty, preserve a safe starting setting.
update public.planner_settings
set start_date = coalesce(start_date, date '2026-09-17'),
    allow_weekends = true,
    updated_at = now()
where id = 1;

