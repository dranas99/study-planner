-- 1) Reorder only FUTURE / incomplete sessions.
--    It never deletes sessions and never changes completed history.
create or replace function public.rebuild_schedule_internal()
returns integer
language plpgsql
security definer
set search_path = public,extensions,pg_catalog
as $$
declare
  v_start date;
  v_cursor date;
  v_count integer := 0;
  v_row record;
begin
  select coalesce(start_date,date '2026-09-17')
  into v_start
  from public.planner_settings
  where id=1;

  v_cursor := greatest(
    v_start,
    coalesce(
      (select max(study_date)+1 from public.study_sessions_v2 where completed=true),
      v_start
    )
  );

  for v_row in
    select s.id
    from public.study_sessions_v2 s
    join public.courses_v2 c on c.id=s.course_id
    where s.completed=false
    order by c.global_order nulls last, c.id, s.study_date, s.id
  loop
    while extract(isodow from v_cursor)::integer in (6,7)
       or exists(
         select 1
         from public.planner_day_offs d
         where d.off_date=v_cursor
       )
    loop
      v_cursor := v_cursor + 1;
    end loop;

    update public.study_sessions_v2
    set study_date=v_cursor
    where id=v_row.id;

    v_cursor := v_cursor + 1;
    v_count := v_count + 1;
  end loop;

  return v_count;
end;
$$;

revoke all on function public.rebuild_schedule_internal() from public;

