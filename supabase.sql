create or replace function public.admin_resize_course_schedule(
  p_token text,
  p_session_id uuid,
  p_new_days integer,
  p_duration_min integer,
  p_notes text,
  p_completed boolean
)
returns integer
language plpgsql
security definer
set search_path = public, extensions, pg_catalog
as $$
declare
  v_course_id bigint;
  v_new_days integer := greatest(1, least(30, coalesce(p_new_days,1)));
  v_completed integer := 0;
begin
  if not public.is_admin_token(p_token) then
    raise exception 'Session admin invalide';
  end if;

  select course_id into v_course_id
  from public.study_sessions_v2
  where id = p_session_id;

  if v_course_id is null then
    raise exception 'Séance introuvable';
  end if;

  select count(*) into v_completed
  from public.study_sessions_v2
  where course_id = v_course_id
    and completed = true;

  -- If the edited session is explicitly marked completed, keep at least one completed day.
  if p_completed then
    v_completed := greatest(v_completed, 1);
  end if;

  update public.courses_v2
  set planned_days = v_new_days,
      default_duration_min = greatest(0, coalesce(p_duration_min,90)),
      default_notes = nullif(trim(coalesce(p_notes,'')),'')
  where id = v_course_id;

  if not found then
    raise exception 'Cours introuvable';
  end if;

  return public.rebuild_schedule_internal();
end;
$$;

grant execute on function public.admin_resize_course_schedule(text,uuid,integer,integer,text,boolean) to anon;


